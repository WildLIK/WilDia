def guess_category_from_code(code):
    """SAE J2012 range -> (system_en, system_ru)."""
    letter = code[0]
    digits = code[1:]
    try:
        n = int(digits)
    except ValueError:
        return ("", "")
    if letter == "P":
        if 0 <= n <= 299: return ("Fuel and Air Metering", "Топливо и измерение воздуха")
        if 300 <= n <= 399: return ("Ignition System or Misfire", "Система зажигания / пропуски зажигания")
        if 400 <= n <= 499: return ("Auxiliary Emission Controls", "Дополнительные системы снижения выбросов")
        if 500 <= n <= 599: return ("Vehicle Speed, Idle Control, Auxiliary Inputs", "Скорость, холостой ход, дополнительные входы")
        if 600 <= n <= 699: return ("Computer Output Circuit", "Выходные цепи ЭБУ")
        if n >= 700: return ("Transmission", "Трансмиссия")
    if letter == "B": return ("Body", "Кузов")
    if letter == "C": return ("Chassis", "Шасси")
    if letter == "U": return ("Network / Communication", "Сеть / связь")
    return ("", "")

def clean(s):
    return re.sub(r"\s+", " ", (s or "")).strip()

def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if os.path.exists(OUT):
        os.remove(OUT)
    con = sqlite3.connect(OUT)
    cur = con.cursor()

    cur.executescript("""
    CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
    CREATE TABLE pids (
        mode INTEGER NOT NULL,
        pid INTEGER NOT NULL,
        name_en TEXT NOT NULL,
        name_ru TEXT,
        unit TEXT,
        bytes INTEGER,
        decoder TEXT NOT NULL,
        weight TEXT,
        mult REAL,
        offset REAL,
        formula TEXT,
        category TEXT,
        PRIMARY KEY(mode, pid)
    );
    CREATE TABLE dtc (
        code TEXT NOT NULL,
        scope TEXT NOT NULL,
        group_tag TEXT,
        description TEXT NOT NULL,
        description_ru TEXT,
        long_description TEXT,
        causes TEXT,
        source TEXT NOT NULL,
        PRIMARY KEY(code, scope)
    ) WITHOUT ROWID;
    CREATE INDEX idx_dtc_code ON dtc(code);
    CREATE TABLE dtc_categories (
        prefix TEXT PRIMARY KEY,
        system_en TEXT,
        system_ru TEXT,
        description_en TEXT,
        description_ru TEXT
    );
    """)

    # ---------------- PIDs ----------------
    for yaml_name, mode in (("mode01.yaml", 1), ("mode09.yaml", 9)):
        with open(os.path.join(OBDEX, "pids", yaml_name), encoding="utf-8") as f:
            entries = yaml.safe_load(f)
        for e in entries:
            pid = e["pid"].upper()
            name_en = clean(e["name"]["en"])
            ru_key = pid if mode == 1 else "M9_" + pid
            name_ru = PID_RU.get(ru_key)
            formula = e.get("formula")
            if formula and formula != "BITMAP":
                formula = clean(formula)
            else:
                formula = None
            if mode == 1 and pid in NUMERIC_DECODER:
                w, m, o = NUMERIC_DECODER[pid]
                decoder = "numeric"
                weight, mult, off = w, m, o
            elif mode == 1 and pid in SPECIAL_DECODER:
                decoder = SPECIAL_DECODER[pid]
                weight = mult = off = None
            elif mode == 9:
                decoder = {"02": "vin", "04": "calid", "06": "cvn", "0A": "ecu_name",
                           "08": "ipt", "0B": "ipt", "0D": "esn", "0E": "esn"}.get(pid, "count")
                weight = mult = off = None
            else:
                decoder = "unsupported"
                weight = mult = off = None
            cur.execute(
                "INSERT INTO pids VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
                (mode, int(pid, 16), name_en, name_ru, e.get("unit"),
                 e.get("bytes"), decoder, weight, mult, off, formula,
                 pid_category(pid) if mode == 1 else "vehicle_info"))

    # ---------------- Generic DTCs from obdex ----------------
    generic_files = ["P0xxx_enriched.yaml", "P2xxx_enriched.yaml", "P3xxx_enriched.yaml",
                     "B0xxx_enriched.yaml", "C0xxx_enriched.yaml",
                     "U0xxx_enriched.yaml", "U3xxx_enriched.yaml"]
    generic_count = 0
    for rel in generic_files:
        path = os.path.join(OBDEX, "generic", rel.replace("/", os.sep))
        if not os.path.exists(path):
            print("WARN: missing", path)
            continue
        with open(path, encoding="utf-8") as f:
            codes = yaml.safe_load(f)
        for c in codes:
            code = c["code"].upper()
            title_en = clean(c.get("title", {}).get("en", ""))
            if not title_en:
                continue
            long_en = clean(c.get("description", {}).get("en", ""))
            if len(long_en) > LONG_DESC_CAP:
                long_en = long_en[:LONG_DESC_CAP].rsplit(" ", 1)[0] + "…"
            causes = []
            for cc in (c.get("common_causes") or [])[:MAX_CAUSES]:
                lab = clean(cc.get("label", {}).get("en", ""))
                if lab:
                    causes.append({"text": lab, "likelihood": cc.get("likelihood", "")})
            cur.execute(
                "INSERT OR IGNORE INTO dtc VALUES (?,?,?,?,?,?,?,?)",
                (code, "GENERIC", "", title_en, DTC_RU.get(code), long_en,
                 json.dumps(causes, ensure_ascii=False) if causes else None,
                 "obdex(CCO)"))
            generic_count += 1

    # ---------------- Wal33D: generic fill + manufacturer ----------------
    wcon = sqlite3.connect(WAL33D_DB)
    fill_count = man_count = 0
    for code, desc in wcon.execute(
            "SELECT code, description FROM dtc_definitions WHERE manufacturer='GENERIC' AND locale='en'"):
        row = cur.execute("SELECT 1 FROM dtc WHERE code=? AND scope='GENERIC'", (code,)).fetchone()
        if not row:
            cur.execute("INSERT INTO dtc VALUES (?,?,?,?,?,?,?,?)",
                        (code, "GENERIC", "", clean(desc), DTC_RU.get(code), None, None, "dtc-database(MIT)"))
            fill_count += 1
    for code, maker, desc in wcon.execute(
            "SELECT code, manufacturer, description FROM dtc_definitions "
            "WHERE manufacturer NOT IN ('GENERIC') AND locale='en'"):
        desc = clean(desc)
        if not desc:
            continue
        tag = "VAG" if maker in VAG_MAKERS else ""
        try:
            cur.execute("INSERT INTO dtc VALUES (?,?,?,?,?,?,?,?)",
                        (code, maker, tag, desc, DTC_RU.get(code), None, None,
                         "dtc-database(MIT)"))
            man_count += 1
        except sqlite3.IntegrityError:
            # same (code, scope) already present
            pass
    wcon.close()

    # ---------------- Categories ----------------
    for prefix, en, ru in CATEGORIES:
        cur.execute("INSERT INTO dtc_categories VALUES (?,?,?,?,?)", (prefix, "", en, "", ru))

    # ---------------- Meta ----------------
    n_pids = cur.execute("SELECT COUNT(*) FROM pids").fetchone()[0]
    n_dtc = cur.execute("SELECT COUNT(*) FROM dtc").fetchone()[0]
    n_generic = cur.execute("SELECT COUNT(*) FROM dtc WHERE scope='GENERIC'").fetchone()[0]
    n_man = cur.execute("SELECT COUNT(*) FROM dtc WHERE scope!='GENERIC'").fetchone()[0]
    n_ru = cur.execute("SELECT COUNT(*) FROM dtc WHERE description_ru IS NOT NULL").fetchone()[0]
    n_makers = cur.execute("SELECT COUNT(DISTINCT scope) FROM dtc WHERE scope!='GENERIC'").fetchone()[0]
    meta = {
        "version": "1.0.0",
        "built_at": "2026-11-20",
        "schema": "1",
        "source_pid": "OBDb/SAEJ1979 + foerbsnavi/obdex (CC0-1.0)",
        "source_dtc_generic": "foerbsnavi/obdex (CC0-1.0), fill: Wal33D/dtc-database (MIT)",
        "source_dtc_manufacturer": "Wal33D/dtc-database (MIT)",
        "pids": str(n_pids),
        "dtc_total": str(n_dtc),
        "dtc_generic": str(n_generic),
        "dtc_manufacturer": str(n_man),
        "dtc_manufacturers": str(n_makers),
        "dtc_ru_translations": str(n_ru),
        "note": "EN descriptions are the authoritative text; RU is a curated factual translation for common codes.",
    }
    for k, v in meta.items():
        cur.execute("INSERT INTO meta VALUES (?,?)", (k, v))

    con.commit()
    cur.execute("VACUUM")
    con.commit()
    con.close()

    size = os.path.getsize(OUT)
    print(f"DB written: {OUT}")
    print(f"  pids: {n_pids}")
    print(f"  dtc total: {n_dtc} (generic {n_generic}, manufacturer {n_man} from {n_makers} makers)")
    print(f"  ru translations: {n_ru}")
    print(f"  obdex generic entries: {generic_count}, wal33d generic fill: {fill_count}, wal33d manufacturer: {man_count}")
    print(f"  size: {size/1024/1024:.2f} MB")

if __name__ == "__main__":
    main()
